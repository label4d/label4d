import { test, expect } from '@playwright/test';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

test('top dataset switch restores KITTI edits after browsing Waymo and fits mobile', async ({ page }) => {
  test.setTimeout(150_000);
  const root = fileURLToPath(new URL('../public/', import.meta.url));
  test.skip(!existsSync(root+'kitti-camera/manifest.json') || !existsSync(root+'datasets/waymo-normalized-198/sequence.json'), 'Prepare real KITTI and Waymo assets');
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(String(error)));
  await page.goto('/?keep=1');
  const selector = page.getByRole('combobox', { name: '切换数据集' });
  await expect(selector).toHaveValue('/kitti-camera/manifest.json');
  await expect(page.getByRole('status', { name: '本地保存状态' })).toContainText('已保存 r0');
  await page.locator('.object-select').first().click();
  const x = page.getByLabel('x', { exact: true });
  const changed = (Number(await x.inputValue()) + 1).toFixed(2);
  await x.fill(changed); await x.press('Tab');
  await expect(page.getByRole('status', { name: '本地保存状态' })).toContainText('已保存 r1');
  await selector.selectOption('/datasets/waymo-normalized-198/sequence.json');
  await expect(page).toHaveURL(/manifest=.*waymo-normalized-198/);
  expect(new URL(page.url()).searchParams.get('keep')).toBe('1');
  await expect(page.getByRole('status', { name: '本地保存状态' })).toContainText('只读浏览', { timeout: 60000 });
  await expect(selector).toBeEnabled(); await expect(selector).toHaveValue('/datasets/waymo-normalized-198/sequence.json');
  await expect(page.getByLabel('选择相机 5')).toBeVisible();
  await expect(page.locator('.camera-empty')).toHaveCount(0);
  await page.screenshot({ path: 'test-results/dataset-switch-waymo.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(selector).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const rect = (await selector.boundingBox())!; expect(rect.x).toBeGreaterThanOrEqual(0); expect(rect.x+rect.width).toBeLessThanOrEqual(390);
  const inspector = (await page.getByRole('button', { name: '切换属性面板' }).boundingBox())!;
  expect(inspector.x + inspector.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: 'test-results/dataset-switch-mobile.png' });
  await selector.selectOption('/kitti-camera/manifest.json');
  await expect(page.getByRole('status', { name: '本地保存状态' })).toContainText('已保存 r1', { timeout: 60000 });
  await page.setViewportSize({ width: 1280, height: 720 });
  if (!await page.getByRole('complementary', { name: '对象与属性' }).isVisible()) await page.getByRole('button', { name: '切换属性面板' }).click();
  await page.locator('.object-select').first().click();
  await expect(page.getByLabel('x', { exact: true })).toHaveValue(changed);
  await expect(page.getByRole('button', { name: '3D框', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: '↩ 撤销', exact: true }).click();
  await expect(page.getByRole('status', { name: '本地保存状态' })).toContainText('已保存 r2');
  await page.screenshot({ path: 'test-results/dataset-switch-kitti.png' });
  expect(errors).toEqual([]);
});
